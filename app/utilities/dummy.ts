// ========== JAMU FUNCTIONS ==========

/**
 * Get semua data jamu
 */
export const getJamuAll = () => {
  return dummyJamu.data;
};

/**
 * Get jamu berdasarkan ID
 * @param id - ID dari jamu
 */
export const getJamuById = (id: number) => {
  return dummyJamu.data.find((jamu) => jamu.id === id);
};

// ========== PRODUCTS FUNCTIONS ==========

/**
 * Get semua produk
 */
export const getProductsAll = () => {
  return dummyProducts.data;
};

/**
 * Get produk berdasarkan ID
 * @param id - ID dari produk
 */
export const getProductById = (id: number) => {
  return dummyProducts.data.find((product) => product.id === id);
};

/**
 * Get produk berdasarkan kategori ID
 * @param categoryId - ID kategori
 */
export const getProductsByCategory = (categoryId: string | number) => {
  return dummyProducts.data.filter(
    (product) => product.category_id === String(categoryId),
  );
};

/**
 * Get produk popular
 */
export const getPopularProducts = (limit?: number) => {
  const popular = dummyProducts.data.filter(
    (product) => product.is_popular === 1,
  );
  return limit ? popular.slice(0, limit) : popular;
};
